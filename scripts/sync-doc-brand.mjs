import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const markPath = path.join(repositoryRoot, "apps/web/public/brand/sivali-mark.svg");
const bannerPath = path.join(repositoryRoot, "docs/assets/orcasynapse-wordmark.svg");

const mark = await readFile(markPath, "utf8");
const match = mark.match(/<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/u);
if (!match?.[1]) throw new Error(`Unable to read the SVG body from ${markPath}`);

const markBody = match[1].trim();
const banner = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="320" viewBox="0 0 1200 320" role="img" aria-labelledby="title description">
  <title id="title">OrcaSynapse</title>
  <desc id="description">OrcaSynapse coordinates models, private knowledge, memory, policy, and governed tools inside infrastructure you control.</desc>
  <!-- Generated by scripts/sync-doc-brand.mjs from apps/web/public/brand/sivali-mark.svg. -->
  <rect x="1" y="1" width="1198" height="318" rx="20" fill="#101118" stroke="#292b35" stroke-width="2"/>
  <g transform="translate(56 52) scale(.576)" aria-hidden="true">
${markBody}
  </g>
  <text x="330" y="133" fill="#f7f7fb" font-family="Inter, Segoe UI, Arial, sans-serif" font-size="72" font-weight="700" letter-spacing="-3">OrcaSynapse</text>
  <text x="334" y="180" fill="#b8bac7" font-family="Inter, Segoe UI, Arial, sans-serif" font-size="20" font-weight="600" letter-spacing="1.2">PRIVATE AGENTIC INTELLIGENCE · GOVERNED EXECUTION · ON-PREMISES</text>
  <path d="M334 211h746" stroke="#353845" stroke-width="2"/>
  <text x="334" y="251" fill="#9a72ff" font-family="Inter, Segoe UI, Arial, sans-serif" font-size="19" font-weight="600">Models  ·  Knowledge  ·  Memory  ·  Policy  ·  Tools  ·  Audit</text>
</svg>
`;

if (process.argv.includes("--check")) {
  const current = await readFile(bannerPath, "utf8").catch(() => "");
  if (current !== banner) {
    console.error("docs/assets/orcasynapse-wordmark.svg is out of sync with the application Orca mark.");
    console.error("Run: node scripts/sync-doc-brand.mjs");
    process.exitCode = 1;
  }
} else {
  await writeFile(bannerPath, banner, "utf8");
  console.log("Updated docs/assets/orcasynapse-wordmark.svg from the application Orca mark.");
}
